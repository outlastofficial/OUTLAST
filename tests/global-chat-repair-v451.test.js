'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const currentBuild=(html.match(/<meta name="outlast-build" content="([^"]+)"/)||[])[1];
function check(ok,message){assert.ok(ok,message);}
const start=html.indexOf('<style id="globalChatEverywhereStyles">');
const end=html.indexOf('<script src="outlast-v32797',start);
check(start>=0&&end>start,'Global Chat widget is present');
const overlay=html.slice(start,end);
check(overlay.includes("const api=apiBase+'/api/chat';"),'Global Chat reads/writes through the server API');
check(overlay.includes('OUTLAST_CHAT_HTTP_BASE'),'Floating chat shares the active chat backend');
check(overlay.includes('outlast-test-server.onrender.com')&&overlay.includes('outlast-server.onrender.com'),'Both backend targets are defined');
check(!overlay.includes('globalChatMessages')&&!overlay.includes('globalChatInput')&&!overlay.includes('sendGlobalChatMessage'),'Broken legacy DOM bridge references are removed');
check(overlay.includes('OWNER')&&overlay.includes('TESTER')&&overlay.includes('m.role'),'Floating chat displays role tags');
const backendAt=html.indexOf('function outlastChatBackendForHost');
check(backendAt>=0,'Host-based backend routing helper is present');
const scriptOpen=html.lastIndexOf('<script',backendAt);
const scriptStart=html.indexOf('>',scriptOpen)+1;
const scriptEnd=html.indexOf('</script>',backendAt);
check(scriptOpen>=0&&scriptEnd>scriptStart,'Chat backend helper is inside a valid script tag');
new vm.Script(html.slice(scriptStart,scriptEnd),{filename:'OUTLAST chat backend inline script'});
check(html.includes("role:String(entry.role||'')"),'Client message state preserves server roles');
check(html.includes("badge.textContent=owner?' 👑 OWNER':' 🧪 TESTER'"),'In-game chat renders OWNER and TESTER badges');
check(currentBuild&&html.includes("const CURRENT_UPDATE_VERSION='"+currentBuild+"'")&&html.includes("title:'v"+currentBuild+" — Shield Stacking & Mobile Control Fix'"),'Update popup follows the current release');
check(html.includes('<meta name="build-version" content="'+currentBuild+'">')&&html.includes('<title>OUTLAST v'+currentBuild+'</title>'),'Visible Survivor Hub marker matches the release metadata');
check(html.includes('v4.5.1 — Global Chat Repair'),'Release notes include chat repair');
const inline=overlay.match(/<script>([\s\S]*?)<\/script>/i);
check(inline&&inline[1],'Floating chat script exists');
new vm.Script(inline[1],{filename:'Global Chat inline script'});
console.log('OUTLAST Global Chat source regression checks passed.');
