const fs=require('fs'),assert=require('assert'),path=require('path'),vm=require('vm');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const maps=fs.readFileSync(path.join(root,'outlast-v430-world-maps.js'),'utf8');
const renderer=fs.readFileSync(path.join(root,'outlast-v434-distinct-map-renderer.js'),'utf8');
assert(html.includes('<meta name="outlast-build" content="4.3.4">'),'visible build marker must be v4.3.4');
assert(html.includes("const BUILD='4.3.4',ACK='outlast_update_ack_v4.3.4'"),'mandatory update acknowledgement must match the visual release');
assert(html.includes('outlast-v434-distinct-map-renderer.js?v=4.3.4'),'distinct map renderer is wired into the game');
assert(html.indexOf('outlast-v434-distinct-map-renderer.js?v=4.3.4')>html.indexOf('outlast-v432-upgrade-ui-hotfix.js?v=4.3.4'),'renderer loads after previous UI modules');
new vm.Script(renderer,{filename:'outlast-v434-distinct-map-renderer.js'});
const added=[...maps.matchAll(/^\s*'([^|]+)\|/gm)].map(m=>m[1]);
assert.strictEqual(added.length,82,'82 added maps are declared');
assert.strictEqual(new Set(added).size,82,'all added map names are unique');
const base=['Seizure','Ribhouse','Forest','Desert','Snow','Lava','City','Hospital','Laboratory','Subway','Prison','MilitaryBase','RuinedTown','Harbor','Bunker','Swamp','Skyscraper','Wasteland'];
assert(!added.some(n=>base.includes(n)),'new maps do not overwrite base maps');
const defs=Object.fromEntries(base.map(n=>[n,{bg:'#172019',grid:'#243428',accent:'#65c27a'}]));
const obstacles=Object.fromEntries(base.map(n=>[n,[['Rock',100,100,100,100]]]));
const hazards=Object.fromEntries(base.map(n=>[n,{name:'Base hazard',color:'#65c27a',interval:18,damage:7,slow:0}]));
const metas={'meta[name="outlast-build"]':{content:'4.3.3'},'meta[name="build-version"]':{content:'4.3.3'}};
const doc={readyState:'complete',title:'OUTLAST v4.3.3',querySelector:s=>metas[s]||null,querySelectorAll:()=>[],addEventListener:()=>{}};
const w={OUTLAST_BUILD:'4.3.3',OUTLAST_VERSION:'v4.3.3',OUTLAST_MAP_CATALOG:base.concat(added),addEventListener:()=>{},drawMapDetails:function(){},drawMapObjects:function(){}};
const sandbox={window:w,document:doc,mapDefs:defs,mapObstacles:obstacles,mapHazards:hazards,save:{map:'Forest'},updates:[],helpArticles:[],console,setTimeout:()=>0,Math,Date,Number,String,Object,Array,Set,JSON,Map,Promise};
sandbox.drawMapDetails=w.drawMapDetails;sandbox.drawMapObjects=w.drawMapObjects;
vm.runInNewContext(renderer,sandbox,{timeout:2500});
const audit=w.OUTLAST_MAP_VISUAL_AUDIT_V434();
assert.strictEqual(audit.added,82,'renderer sees all 82 added maps');
assert.strictEqual(audit.uniqueAdded,82,'new map names remain unique');
assert.strictEqual(audit.distinctPalettes,82,'every added map must have its own palette');
assert.strictEqual(audit.distinctLayouts,82,'every added map must have its own obstacle layout');
assert.strictEqual(audit.missingThemes.length,0,'no added map is missing a theme');
assert.strictEqual(audit.missingLayouts.length,0,'no added map is missing a layout');
assert.strictEqual(audit.drawMapDetailsWrapped,true,'terrain patterns are connected to the actual renderer');
assert.strictEqual(audit.drawMapObjectsWrapped,true,'themed prop rendering is connected to the actual renderer');
assert.strictEqual(audit.ready,true,'all 82 map visuals pass the audit');
assert.strictEqual(w.OUTLAST_BUILD,'4.3.4','visual module preserves the release version');
console.log('OUTLAST v4.3.4 distinct-map visuals test passed: 82 palettes, 82 layouts, themed terrain and object renderers.');
